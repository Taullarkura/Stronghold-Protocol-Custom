#!/usr/bin/env node
// tools/update-notice.mjs — the title screen's 更新公告 is written as a markdown note, then generated into the screen.
//
// The note (todoList/更新公告.md) is the maintainer's private draft: `todoList/` is gitignored, so the note never ships
// and never enters a language pack. Its `### v<版本>` headings are releases, `- ` lines are the bullets, a `##### 势力`
// heading under a release makes that faction its own group, and a bare paragraph line under the bullets (拉特兰's
// `<在场6名…>` line) becomes the group's `detail`.
//
//   node tools/update-notice.mjs             regenerate the block in public/js/screens/title.js
//   node tools/update-notice.mjs --check     exit 1 when the block does not match the note (skipped when it is absent)
//   node tools/update-notice.mjs --file 其他.md --target 其他.js
//
// Only the block between `// update-notice:start` and `// update-notice:end` is generated; the heading, the dialog and
// the "seen" preference stay hand-written. Run `npm run notice` after editing the note.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

export const NOTE_FILE = 'todoList/更新公告.md';
export const TARGET_FILE = 'public/js/screens/title.js';
export const START = '// update-notice:start';
export const END = '// update-notice:end';

const RELEASE = /^###\s+(\S.*)$/;
const SUBHEADING = /^####\s+(\S.*)$/;
const FACTION = /^#####\s+(\S.*)$/;

/**
 * Parse the note into releases, newest first as written: `{ version, groups: [{ name, items, detail }] }`, where a
 * `name` of null is a flat bullet list that gets the release's own title.
 * @param {string} markdown
 */
export function parseNote(markdown) {
  const releases = [];
  let release = null;
  let group = null;
  const open = (name) => {
    const fresh = { name, items: [], lines: [] };
    release.groups.push(fresh);
    return fresh;
  };
  for (const raw of String(markdown ?? '').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    const head = RELEASE.exec(line);
    if (head) {
      release = { version: head[1].trim().replace(/^v/i, ''), groups: [] };
      releases.push(release);
      group = null;
      continue;
    }
    if (!release) continue;
    const faction = FACTION.exec(line);
    if (faction) { group = open(faction[1].trim()); continue; }
    if (SUBHEADING.test(line)) { group = null; continue; }
    if (line.startsWith('- ')) {
      // consecutive bullets with no ##### heading above them are one flat group of the release
      if (!group) group = release.groups[release.groups.length - 1]?.name === null ? release.groups[release.groups.length - 1] : open(null);
      const item = line.slice(2).trim();
      if (item) group.items.push(item);
      continue;
    }
    if (group) group.lines.push(line);
  }
  for (const r of releases) for (const g of r.groups) g.detail = g.lines.length ? g.lines.join(' ') : null;
  return releases;
}

/** One group per release (a flat list) or per faction, titled `v<版本> · <势力>` so the version stays visible. */
export function noticeGroups(releases) {
  return releases.flatMap((r) => r.groups.map((g) => ({
    title: g.name ? `v${r.version} · ${g.name}` : `v${r.version}`,
    items: [...g.items],
    detail: g.detail,
  })));
}

const quote = (text) => `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** The generated block, markers included. */
export function renderBlock(releases) {
  const version = releases[0]?.version;
  if (!version) throw new Error('the note has no `### v<版本>` release heading');
  const lines = [
    `${START} — generated by tools/update-notice.mjs from ${NOTE_FILE}; edit the note, then run \`npm run notice\``,
    `export const UPDATE_NOTICE_VERSION = ${quote(version)};`,
    'export const UPDATE_NOTICE_CONTENT = [',
  ];
  for (const group of noticeGroups(releases)) {
    lines.push('  {', `    title: ${quote(group.title)},`, '    items: [');
    for (const item of group.items) lines.push(`      ${quote(item)},`);
    lines.push('    ],');
    if (group.detail) lines.push(`    detail: ${quote(group.detail)},`);
    lines.push('  },');
  }
  lines.push('];', END);
  return lines.join('\n');
}

/** Replace the marked block of `source`; throws when the markers are missing. */
export function replaceBlock(source, block) {
  const start = source.indexOf(START);
  const end = source.indexOf(END, start);
  if (start < 0 || end < 0) throw new Error(`no ${START} … ${END} markers to fill`);
  return source.slice(0, start) + block + source.slice(end + END.length);
}

function main(argv) {
  const arg = (name, fallback) => {
    const i = argv.indexOf(`--${name}`);
    return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
  };
  const notePath = join(ROOT, arg('file', NOTE_FILE));
  const targetPath = join(ROOT, arg('target', TARGET_FILE));
  const label = relative(ROOT, notePath);

  let note;
  try {
    note = readFileSync(notePath, 'utf8');
  } catch (error) {
    // the note is a private, gitignored draft: a checkout without it still builds, and --check simply has nothing to say
    console.log(`update-notice: ${label} is not here (${error.code}) — the note is a local draft, nothing to do`);
    return 0;
  }
  const block = renderBlock(parseNote(note));
  const target = readFileSync(targetPath, 'utf8');
  const next = replaceBlock(target, block);
  const groups = noticeGroups(parseNote(note)).length;

  if (argv.includes('--check')) {
    if (next === target) {
      console.log(`update-notice: ${relative(ROOT, targetPath)} matches ${label} (${groups} groups)`);
      return 0;
    }
    console.error(`update-notice: ${relative(ROOT, targetPath)} is out of date with ${label} — run \`npm run notice\``);
    return 1;
  }
  if (next === target) {
    console.log(`update-notice: ${relative(ROOT, targetPath)} already matches ${label} (${groups} groups)`);
    return 0;
  }
  writeFileSync(targetPath, next, 'utf8');
  console.log(`update-notice: wrote ${groups} groups from ${label} into ${relative(ROOT, targetPath)}`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
