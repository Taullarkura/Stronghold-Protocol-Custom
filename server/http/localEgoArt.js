// server/http/localEgoArt.js — the E.G.O 饰品 / 苦难 icons this installation has (DESIGN §F16 "The icons").
//
// The art is game art, so it is not in git: a player drops one file per record into public/assets/local/ego/, named after
// the record id (public/assets/local/ego/dust-to-dust.png; custom_tools/download-egogift.cjs fetches them there), and
// public/assets/local/** is never pruned by tools/fetch-assets.mjs. The files become a `group` of the served
// data/local-assets.json (assetViews.js), hashed like any other art, so the client reads them through localAsset() as it
// reads every other local sprite — and a record with no file simply has no entry, so no request and no 404 is made: the
// card falls back to its glyph.
//
// This module only reads the directory; it never writes (data/local-assets.json is generated by tools/build-data.mjs and
// the ego group is this machine's, not part of the data set).

import fsp from 'node:fs/promises';
import path from 'node:path';

/** The group name inside data/local-assets.json. */
export const EGO_ART_GROUP = 'ego';
/** Where the files live, under the served public directory. */
export const EGO_ART_DIR = path.join('assets', 'local', 'ego');
/** The extensions accepted as an icon, in the order one file name may have several of. */
export const EGO_ART_EXTS = Object.freeze(['.png', '.webp', '.avif', '.jpg', '.jpeg', '.gif']);
/** The manifest entry kind the client's local sprite layer reads (the same 'Sprite' local UI art uses). */
const ENTRY_KIND = 'Sprite';

/**
 * The pixel size of a PNG, or null (the other formats are served without it: the card sizes the picture itself).
 * @param {Buffer} buf the first bytes of the file
 * @returns {{ w: number, h: number } | null}
 */
function pngSize(buf) {
  if (buf.length < 24 || buf.readUInt32BE(0) !== 0x89504e47 || buf.toString('ascii', 12, 16) !== 'IHDR') return null;
  const w = buf.readUInt32BE(16);
  const h = buf.readUInt32BE(20);
  return w > 0 && h > 0 ? { w, h } : null;
}

/** One file of the directory → its manifest entry, or null when the name is not a record id. */
function entryOf(file) {
  const ext = path.extname(file).toLowerCase();
  if (!EGO_ART_EXTS.includes(ext)) return null;
  const id = path.basename(file, path.extname(file));
  // a record id: lowercase letters, digits and dashes (shared/ego.js ids like `dust-to-dust`, `sharpness-1`)
  if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) return null;
  return { id, ext, file };
}

/**
 * The icons on disk, or null when this installation has none (the manifest view then keeps exactly the bytes it had).
 * @param {string | null | undefined} publicDir the served public directory (server/index.js)
 * @returns {Promise<{ entries: Record<string, { path: string, w?: number, h?: number, kind: string }>, stamp: string } | null>}
 */
export async function readEgoArt(publicDir) {
  if (!publicDir) return null;
  const dir = path.join(path.resolve(publicDir), EGO_ART_DIR);
  /** @type {import('node:fs').Dirent[]} */
  let list;
  try { list = await fsp.readdir(dir, { withFileTypes: true }); } catch { return null; }
  const files = list.filter((d) => (d.isFile() || d.isSymbolicLink()) && entryOf(d.name)).map((d) => d.name).sort();
  if (!files.length) return null;
  /** @type {Record<string, any>} */
  const entries = {};
  const stamps = [];
  for (const file of files) {
    const found = entryOf(file);
    if (!found) continue;
    const abs = path.join(dir, file);
    let st;
    try { st = await fsp.stat(abs); } catch { continue; }
    if (!st.isFile()) continue;
    // the record id names the file; a second extension for the same id (icon.png next to icon.webp) keeps the first
    if (Object.hasOwn(entries, found.id)) continue;
    const entry = { path: `/assets/local/ego/${encodeURIComponent(file)}`, kind: ENTRY_KIND };
    if (found.ext === '.png') {
      /** @type {Buffer | null} */
      let head;
      try {
        const fh = await fsp.open(abs, 'r');
        try { head = Buffer.alloc(24); await fh.read(head, 0, 24, 0); } finally { await fh.close(); }
      } catch { head = null; }
      const size = head ? pngSize(head) : null;
      if (size) { entry.w = size.w; entry.h = size.h; }
    }
    entries[found.id] = entry;
    stamps.push(`${file}:${st.size}:${Math.trunc(st.mtimeMs)}`);
  }
  if (!Object.keys(entries).length) return null;
  // the cache key of the manifest view: any icon added, replaced or removed rebuilds it
  return { entries, stamp: stamps.join('|') };
}

/**
 * The local manifest with the E.G.O icons as its `ego` group. A copy: the parsed file is never changed, and with no
 * icons the caller has already returned before reaching here (so an installation without art serves the same bytes).
 * @param {any} doc the parsed data/local-assets.json (or the empty stand-in)
 * @param {Record<string, any>} entries readEgoArt().entries
 */
export function withEgoArt(doc, entries) {
  const base = doc && typeof doc === 'object' && !Array.isArray(doc) ? doc : {};
  const groups = base.groups && typeof base.groups === 'object' && !Array.isArray(base.groups) ? base.groups : {};
  const own = groups[EGO_ART_GROUP] && typeof groups[EGO_ART_GROUP] === 'object' && !Array.isArray(groups[EGO_ART_GROUP])
    ? groups[EGO_ART_GROUP] : {};
  let added = 0;
  const next = { ...own };
  for (const [id, e] of Object.entries(entries)) {
    if (Object.hasOwn(next, id)) continue;
    next[id] = e;
    added++;
  }
  if (!added) return base;
  const count = typeof base.count === 'number' && Number.isFinite(base.count) ? base.count + added : base.count;
  return { ...base, ...(count === undefined ? {} : { count }), groups: { ...groups, [EGO_ART_GROUP]: next } };
}
